def ensure():
	import frappe

	for source, pair in WORDS.items():
		for lang, idx in (("hi", 0), ("mr", 1)):
			if not frappe.db.exists("Language", lang):
				continue
			existing = frappe.db.get_value("Translation", {"language": lang, "source_text": source}, "name")
			if existing:
				frappe.db.set_value("Translation", existing, "translated_text", pair[idx])
			else:
				frappe.get_doc({"doctype": "Translation", "language": lang, "source_text": source,
				                "translated_text": pair[idx]}).insert(ignore_permissions=True)
